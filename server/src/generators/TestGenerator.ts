import { ApiEndpoint, Project } from '../types/index.js';

export class TestGenerator {
  public static generateTestSuite(project: Project, endpoints: ApiEndpoint[]): string {
    let code = `// =========================================================================\n`;
    code += `// Automated API Test Suite for ${project.name}\n`;
    code += `// Framework: Jest + Supertest\n`;
    code += `// Generated by AI API Reverse-Engineering Platform\n`;
    code += `// =========================================================================\n\n`;

    code += `import request from 'supertest';\n`;
    code += `// Import your Express application instance:\n`;
    code += `import app from '../src/index';\n\n`;

    code += `describe('${project.name} API Test Suite', () => {\n`;
    code += `  const authToken = 'TEST_JWT_TOKEN_SAMPLE';\n\n`;

    endpoints.forEach((ep) => {
      const testPath = ep.path.replace(/:([a-zA-Z0-9_]+)/g, '1');
      const bodyParams = ep.parameters.filter((p) => p.paramIn === 'body');
      const samplePayload: Record<string, any> = {};
      bodyParams.forEach((bp) => {
        samplePayload[bp.name] = bp.defaultValue || (bp.dataType === 'number' ? 42 : `${bp.name}_test`);
      });

      code += `  describe('${ep.method} ${ep.path}', () => {\n`;

      // Test 1: Happy path
      code += `    it('should return expected status code on valid request', async () => {\n`;
      code += `      const res = await request(app)\n`;
      code += `        .${ep.method.toLowerCase()}('${testPath}')\n`;
      if (ep.authRequired) {
        code += `        .set('Authorization', \`Bearer \${authToken}\`)\n`;
      }
      if (['POST', 'PUT', 'PATCH'].includes(ep.method) && bodyParams.length > 0) {
        code += `        .send(${JSON.stringify(samplePayload)})\n`;
      }
      const successStatus = ep.responses.find((r) => r.statusCode < 300)?.statusCode || (ep.method === 'POST' ? 201 : 200);
      code += `        .expect((res) => {\n`;
      code += `          expect([${successStatus}, 200, 201, 204]).toContain(res.status);\n`;
      code += `        });\n`;
      code += `    });\n\n`;

      // Test 2: Auth Gate check if protected
      if (ep.authRequired) {
        code += `    it('should reject request with 401 when token is missing', async () => {\n`;
        code += `      const res = await request(app)\n`;
        code += `        .${ep.method.toLowerCase()}('${testPath}')\n`;
        if (['POST', 'PUT', 'PATCH'].includes(ep.method) && bodyParams.length > 0) {
          code += `        .send(${JSON.stringify(samplePayload)})\n`;
        }
        code += `        .expect(401);\n`;
        code += `      expect(res.body).toBeDefined();\n`;
        code += `    });\n\n`;
      }

      // Test 3: Missing required field check if body params exist
      if (['POST', 'PUT'].includes(ep.method) && bodyParams.length > 0) {
        code += `    it('should handle invalid or empty payload with 400 Bad Request', async () => {\n`;
        code += `      const res = await request(app)\n`;
        code += `        .${ep.method.toLowerCase()}('${testPath}')\n`;
        if (ep.authRequired) {
          code += `        .set('Authorization', \`Bearer \${authToken}\`)\n`;
        }
        code += `        .send({})\n`;
        code += `        .expect((res) => {\n`;
        code += `          expect([400, 422]).toContain(res.status);\n`;
        code += `        });\n`;
        code += `    });\n\n`;
      }

      code += `  });\n\n`;
    });

    code += `});\n`;
    return code;
  }
}
