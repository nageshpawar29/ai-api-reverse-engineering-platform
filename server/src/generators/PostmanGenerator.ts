import { ApiEndpoint, Project } from '../types/index.js';

export class PostmanGenerator {
  public static generateCollection(project: Project, endpoints: ApiEndpoint[]): any {
    const items = endpoints.map((ep) => {
      // Split path into segments
      const cleanPath = ep.path.startsWith('/') ? ep.path.slice(1) : ep.path;
      const pathSegments = cleanPath.split('/').map((seg) => {
        if (seg.startsWith(':')) {
          return `:${seg.slice(1)}`;
        }
        return seg;
      });

      // Headers
      const headerList: any[] = [
        {
          key: 'Content-Type',
          value: 'application/json',
          type: 'text',
        },
      ];

      // Query params
      const queryList: any[] = [];
      const pathVariables: any[] = [];
      const bodyParams: any[] = [];

      ep.parameters.forEach((param) => {
        if (param.paramIn === 'query') {
          queryList.push({
            key: param.name,
            value: param.defaultValue || '',
            description: param.description || '',
          });
        } else if (param.paramIn === 'path') {
          pathVariables.push({
            key: param.name,
            value: 'sample_id',
            description: param.description || '',
          });
        } else if (param.paramIn === 'body') {
          bodyParams.push(param);
        }
      });

      // Request Body
      let bodyData: any = undefined;
      if (['POST', 'PUT', 'PATCH'].includes(ep.method) && bodyParams.length > 0) {
        const sampleBody: Record<string, any> = {};
        bodyParams.forEach((bp) => {
          sampleBody[bp.name] = bp.defaultValue || (bp.dataType === 'number' ? 100 : `${bp.name}_value`);
        });

        bodyData = {
          mode: 'raw',
          raw: JSON.stringify(sampleBody, null, 2),
          options: {
            raw: {
              language: 'json',
            },
          },
        };
      }

      // Authentication
      const auth = ep.authRequired
        ? {
            type: 'bearer',
            bearer: [
              {
                key: 'token',
                value: '{{bearerToken}}',
                type: 'string',
              },
            ],
          }
        : undefined;

      return {
        name: `${ep.method} ${ep.path}`,
        request: {
          auth,
          method: ep.method,
          header: headerList,
          body: bodyData,
          url: {
            raw: `{{baseUrl}}/${cleanPath}`,
            host: ['{{baseUrl}}'],
            path: pathSegments,
            query: queryList.length > 0 ? queryList : undefined,
            variable: pathVariables.length > 0 ? pathVariables : undefined,
          },
          description: ep.purpose || ep.description || `Discovered handler: ${ep.controllerName || ep.handlerFunction}`,
        },
        response: [],
      };
    });

    return {
      info: {
        name: `${project.name} Postman Collection`,
        description: `Generated by AI API Reverse-Engineering Platform for ${project.name}`,
        schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
      },
      variable: [
        {
          key: 'baseUrl',
          value: 'http://localhost:3000',
          type: 'string',
        },
        {
          key: 'bearerToken',
          value: 'YOUR_JWT_TOKEN_HERE',
          type: 'string',
        },
      ],
      item: items,
    };
  }
}
